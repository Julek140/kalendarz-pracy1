export const t = (key, language = 'pl', params = {}) => {
  let text = translations[language]?.[key] || translations['pl']?.[key] || key;
  
  // Replace parameters in text
  Object.keys(params).forEach(param => {
    text = text.replace(`{${param}}`, params[param]);
  });
  
  return text;
};